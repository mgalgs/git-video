#!/usr/bin/env python3
"""Write man/git-video.1 from its two sources: the man-page block that opens
README.md (synopsis, description, modes) and the argparse parser (options).

    python man/mkman.py           # rewrite man/git-video.1
    python man/mkman.py --check   # exit 1 if man/git-video.1 is out of date
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PAGE = os.path.join(HERE, 'git-video.1')
sys.path.insert(0, ROOT)


def readme_block(text):
    """The lines of the first fenced block of the README: the man-page section."""
    m = re.search(r'^```\n(.*?)^```$', text, re.S | re.M)
    return m.group(1).splitlines()


def sections(lines):
    """[(header or None, [lines])], split at the block's `Header:` lines."""
    out = [(None, [])]
    for line in lines:
        m = re.fullmatch(r'([A-Z][a-z]+):', line)
        if m:
            out.append((m.group(1), []))
        else:
            out[-1][1].append(line)
    return out


def paragraphs(lines):
    """Blank-line separated runs of lines, each joined into one string."""
    paras, cur = [], []
    for line in lines + ['']:
        if line.strip():
            cur.append(line.strip())
        elif cur:
            paras.append(' '.join(cur))
            cur = []
    return paras


def terms(lines):
    """[(term, text)] for a block of `term   text` entries with indented continuations,
    then the trailing paragraphs that are not entries."""
    entries, rest, cur = [], [], None
    for line in lines:
        if line.strip() and not line.startswith(' ') and (re.search(r'\S\s{2,}\S', line) or line.startswith('-')):
            term, _, text = re.split(r'(\s{2,}|$)', line, maxsplit=1)
            cur = [term, [text.strip()] if text.strip() else []]
            entries.append(cur)
        elif line.startswith(' ') and cur:
            cur[1].append(line.strip())
        else:
            cur = None
            rest.append(line)
    return [(t, ' '.join(body)) for t, body in entries], paragraphs(rest)


def esc(s):
    """Text made safe for roff: backslashes, hyphens, and a leading control character."""
    s = s.replace('\\', '\\e').replace('-', '\\-')
    return '\\&' + s if s[:1] in ('.', "'") else s


def bold(s):
    return f'\\fB{esc(s)}\\fR'


def options(parser):
    """[(term, help)] for the parser's arguments, in its order (help omitted). The
    parser's help is the full option list; the README's Options summary is not repeated."""
    out = []
    for a in parser._actions:
        if a.help is None or '--help' in a.option_strings:
            continue
        help_ = a.help
        if not a.option_strings:
            term = bold(a.metavar or a.dest)
        else:
            m = re.match(r'(--\S+): (.*)', help_)
            if m:   # help that spells the flag itself, e.g. --verbose[=1,2,3]
                forms, help_ = [m.group(1)], m.group(2)
            else:
                value = ''
                if a.nargs != 0:
                    value = ' ' + ('{' + ','.join(map(str, a.choices)) + '}' if a.choices else a.metavar or a.dest.upper())
                forms = [f + value for f in a.option_strings]
            term = ', '.join(bold(f.split(' ')[0]) + ('\\ \\fI' + esc(f.split(' ', 1)[1]) + '\\fR'
                                                      if ' ' in f else '') for f in forms)
        out.append((term, help_.rstrip('.') + '.'))
    return out


def roff(readme, parser, version):
    secs = sections(readme_block(readme))
    head = paragraphs(secs[0][1])
    usage = head[0].removeprefix('Usage:').strip()
    out = ['.\\" Generated by man/mkman.py from README.md and git_video/cli.py; do not edit.',
           f'.TH GIT\\-VIDEO 1 "" "git\\-video {version}" "Git Manual"', '.nh', '.ad l',
           '.SH NAME', 'git\\-video \\- ' + esc(head[1][:1].lower() + head[1][1:].rstrip('.')),
           '.SH SYNOPSIS', '.nf', esc(usage), '.fi',
           '.SH DESCRIPTION', esc(head[1])]
    out += ['.SH OPTIONS']
    for term, text in options(parser):
        out += ['.TP', term, esc(text)]
    see = []
    for name, lines in secs[1:]:
        if name == 'Options':
            continue   # the parser's help, above, says all of it and more
        entries, rest = terms(lines)
        out.append('.SH ' + esc(name.upper()))
        for term, text in entries:
            out += ['.TP', bold(term), esc(text)]
        for p in rest:
            if p.startswith('Uses '):
                see.append(p.removeprefix('Uses ').strip())
                continue
            out += ['.PP', esc(p)]
    out += ['.SH SEE ALSO', '\\fBgit\\fR(1), \\fBffmpeg\\fR(1)' + ''.join(
        f', {esc(s)} (https://github.com/{esc(s)})' for s in see)]
    return '\n'.join(out) + '\n'


def generate():
    from git_video import __version__, cli
    with open(os.path.join(ROOT, 'README.md')) as f:
        return roff(f.read(), cli.parser(), __version__)


def main(argv):
    text = generate()
    if '--check' in argv:
        with open(PAGE) as f:
            if f.read() != text:
                print(f'{PAGE} is out of date: run python man/mkman.py', file=sys.stderr)
                return 1
        return 0
    with open(PAGE, 'w') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
